<p>Drain the soapy water and refill with clean, cool water at the same temperature. Temperature shock—moving from warm wash water to cold rinse water—can cause shrinkage just as surely as hot water alone. Gently press the garment to release soap, then repeat the rinse until water runs clear.</p>

