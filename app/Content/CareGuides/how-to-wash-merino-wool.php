<p>Modern washing machines with dedicated wool or delicate cycles can successfully clean merino wool when used correctly. This option works well for those short on time, though hand washing still provides the gentlest care.</p>

<p>Select your machine's wool, delicate, or hand-wash cycle—these programs minimize agitation and use appropriate spin speeds. If your machine lacks these options, the shortest, gentlest cycle with a slow or no-spin setting works as an alternative.</p>

