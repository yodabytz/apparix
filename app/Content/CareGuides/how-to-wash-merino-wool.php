<h2>Understanding Why Wool Shrinks</h2>

<p>Before diving into washing techniques, understanding why wool shrinks helps prevent it. Wool fibers have microscopic scales along their surface. When exposed to heat, moisture, and agitation simultaneously, these scales interlock permanently—a process called felting. Once felted, the damage cannot be fully reversed. The key to preventing shrinkage lies in controlling these three factors throughout the washing process.</p>

<p>Merino wool, despite being finer than standard wool, follows the same principles. Its delicate nature actually makes it more susceptible to damage from rough handling, making gentle care even more essential.</p>

<h2>The Hand Washing Method: Gold Standard for Wool Care</h2>

<p>Hand washing remains the safest and most effective method for cleaning merino wool. This approach gives you complete control over water temperature, detergent concentration, and handling throughout the process.</p>

<h3>Step-by-Step Hand Washing Process</h3>

<p>Begin by filling a clean basin or sink with cool to lukewarm water—never exceeding 30°C (86°F). Add a small amount of wool-specific detergent or a pH-neutral soap. Standard laundry detergents contain enzymes and harsh chemicals that can damage wool fibers and strip away natural lanolin.</p>

<p>Turn your garment inside out to protect the outer surface, then submerge it fully in the water. Allow the piece to soak for 10 to 15 minutes without any agitation. This soaking period lets the detergent work into the fibers and loosens dirt without mechanical stress.</p>

