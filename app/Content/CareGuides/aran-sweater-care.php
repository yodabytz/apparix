<h2>Addressing Common Issues</h2>

<h3>Pilling</h3>

<p>Surface pilling occurs naturally with wool wear, particularly in friction areas. A fabric shaver or sweater stone removes pills effectively. Work gently across the surface, allowing the tool to do the work rather than pressing hard. Regular maintenance keeps cables looking sharp and defined.</p>

<h3>Pulled Threads</h3>

<p>Snagged threads happen, especially in textured knits. Never cut a pulled thread—this leads to unraveling. Instead, use a blunt tapestry needle or crochet hook from the wrong side of the fabric. Gently ease the excess yarn back into the surrounding stitches, distributing it evenly to minimize the visible defect.</p>

<h3>Stretched Necklines and Cuffs</h3>

