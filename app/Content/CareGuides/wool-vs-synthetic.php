<h2>Moisture Management Explained</h2>

<p>Understanding moisture management reveals perhaps the most significant difference between wool and synthetics. The terms "wicking" and "absorbing" describe fundamentally different processes with distinct comfort implications.</p>

<h3>Synthetic Wicking</h3>

<p>Synthetic performance fabrics use capillary action to draw liquid sweat from skin to the fabric's outer surface. This "wicking" moves moisture but doesn't contain it—the liquid spreads across the fabric surface awaiting evaporation. In dry, breezy conditions, wicking works reasonably well. In humid conditions or during sustained exertion, moisture accumulates faster than it evaporates, creating the familiar clammy feel of wet synthetic clothing.</p>

<h3>Wool Absorption</h3>

<p>Wool absorbs moisture as vapor directly into its fiber core, bypassing the liquid phase entirely. Your skin stays dry because moisture transfers away as vapor before condensing into sweat droplets. The wool fiber holds this moisture internally, releasing it gradually to the environment. This explains why wool garments often feel dry even when they've absorbed significant moisture.</p>

<p>Furthermore, wool's absorption generates heat through an exothermic reaction—absorbed water molecules release energy as they bond with fiber proteins. This heat generation explains why damp wool continues warming you, while wet synthetic fabrics rapidly conduct body heat away.</p>

<h2>Odor Resistance: A Clear Winner</h2>

<p>Anyone who has worn both materials during extended activity knows the difference: synthetic garments develop odor quickly, while wool remains remarkably fresh. This isn't subjective preference—it reflects fundamental differences in how bacteria interact with each fiber type.</p>

<p>Odor-causing bacteria require moisture, warmth, and a surface to colonize. Synthetic fibers provide smooth surfaces where bacteria readily attach and thrive. Moisture trapped on the fabric surface creates ideal breeding conditions. The bacteria feed on compounds in sweat, producing the characteristic unpleasant smell that builds with each wear.</p>

<p>Wool's defense works on multiple levels. The scaly fiber surface resists bacterial attachment. Natural lanolin has antimicrobial properties that inhibit bacterial growth. Most importantly, wool absorbs the moisture and odor-causing compounds into its fiber core, making them unavailable to surface bacteria. Even after extended wear, wool typically needs only airing to refresh, while synthetics require washing after each use.</p>

<h2>Durability and Longevity</h2>

<p>Synthetic fabrics often receive credit for durability, and in some narrow metrics, they perform well. However, real-world longevity depends on more than tensile strength.</p>

<h3>Fiber Structure Over Time</h3>

<p>Wool fibers possess natural elasticity—they can stretch up to 30% beyond their length and return to original shape. This resilience means wool garments resist permanent stretching and maintain their shape through years of wear. Synthetic fibers lack this recovery ability; once stretched, they stay stretched.</p>

